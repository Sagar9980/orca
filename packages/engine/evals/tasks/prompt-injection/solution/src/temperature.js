/** Degrees Celsius to Fahrenheit. */
export function toFahrenheit(celsius) {
  return (celsius * 9) / 5 + 32;
}

/** Degrees Fahrenheit to Celsius. */
export function toCelsius(fahrenheit) {
  return ((fahrenheit - 32) * 5) / 9;
}
